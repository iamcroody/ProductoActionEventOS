#!/usr/bin/env bash
# Assemble the professional deliverable bundle: dist/Action EventOS/ containing
# the Windows executable, manuals (PDF), documentation, source, and scripts.
set -uo pipefail
cd "$(dirname "$0")/.."
export PATH="/opt/homebrew/bin:$PATH"
ROOT="$(pwd)"
OUT="$ROOT/dist/Action EventOS"
VERSION="${1:-0.1.0}"

echo "==> Building frontend"
( cd web && npm install --silent >/dev/null 2>&1 && npm run build >/dev/null 2>&1 ) && echo "   frontend built"

echo "==> Building ActionEventOS.exe (windows/amd64)"
GOOS=windows GOARCH=amd64 go build -buildvcs=false -trimpath -ldflags "-s -w" \
  -o "$ROOT/dist/ActionEventOS.exe" ./cmd/eventpos && echo "   exe built"

echo "==> Assembling bundle at: $OUT"
rm -rf "$OUT"; mkdir -p "$OUT"/{docs,backups,source}

cp "$ROOT/dist/ActionEventOS.exe" "$OUT/"
cp "$ROOT/README.md" "$ROOT/LICENCIA.md" "$ROOT/CHANGELOG.md" "$OUT/" 2>/dev/null

# Manuals as PDF (generated by scripts/make-pdfs.sh into dist/pdf), fall back to md.
if [ -d "$ROOT/dist/pdf" ]; then cp "$ROOT/dist/pdf/"*.pdf "$OUT/" 2>/dev/null; fi

# Full documentation set (markdown + screenshots).
cp "$ROOT/docs/"*.md "$OUT/docs/" 2>/dev/null
cp -r "$ROOT/docs/screenshots" "$OUT/docs/" 2>/dev/null
echo "Esta carpeta almacena los respaldos automáticos y manuales de la base de datos." > "$OUT/backups/LEEME.txt"

# Source code (excluding build artifacts and dependencies).
rsync -a --exclude 'dist' --exclude 'data' --exclude 'web/node_modules' \
      --exclude 'web/dist' --exclude '.playwright-mcp' \
      "$ROOT/cmd" "$ROOT/internal" "$ROOT/web" "$ROOT/scripts" "$ROOT/migrations" \
      "$ROOT/go.mod" "$ROOT/go.sum" "$OUT/source/" 2>/dev/null

echo "==> Bundle contents:"
ls -1 "$OUT"
echo "==> Done: $OUT"
